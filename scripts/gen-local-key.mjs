// .env.local / .env 에서 GEMINI_API_KEY(+선택 GEMINI_MODEL)를 읽어 local-key.js 생성.
//
// local-key.js 는 .gitignore — 브라우저(VS Code "Go Live" 등)에서 index.html 이
// 이 파일을 로드해 localStorage(layer2.llm.*)에 키를 심는다. 데모용. git 에 안 올라감.
//
// 사용: npm run key   (.env.local 수정 후 다시 실행하면 갱신)
import { readFileSync, writeFileSync, existsSync } from "node:fs";

function loadEnv() {
  const env = {};
  for (const f of [".env.local", ".env"]) {
    if (!existsSync(f)) continue;
    for (const line of readFileSync(f, "utf8").split("\n")) {
      const m = line.match(/^\s*([\w.]+)\s*=\s*(.*?)\s*$/);
      if (!m) continue;
      const [, k, raw] = m;
      const v = raw.replace(/^["']|["']$/g, "");
      if (env[k] === undefined) env[k] = v;
    }
  }
  return env;
}

const env = loadEnv();
const key = (env.GEMINI_API_KEY || "").trim();
const model = (env.GEMINI_MODEL || "").trim();

if (!key) {
  console.error(
    "✗ .env.local 에 GEMINI_API_KEY 가 없습니다.\n  예) GEMINI_API_KEY=AIza... (.env.example 참고)",
  );
  process.exit(1);
}

const out = `// AUTO-GENERATED by scripts/gen-local-key.mjs — 직접 수정하지 말 것.
// git 에 안 올라감(.gitignore). 브라우저에서 index.html 이 로드해
// localStorage 에 Gemini 키를 심는다(데모용). 키 바꾸려면 .env.local 수정 후 \`npm run key\`.
(function () {
  try {
    localStorage.setItem("layer2.llm.provider", "gemini");
    localStorage.setItem("layer2.llm.key", ${JSON.stringify(key)});
${model ? `    localStorage.setItem("layer2.llm.model", ${JSON.stringify(model)});\n` : ""}  } catch (e) {}
})();
`;

writeFileSync("local-key.js", out);
console.log(
  `✓ local-key.js 생성 완료${model ? ` (model: ${model})` : ""} — 이제 Go Live 로 열면 키 입력 없이 대화됩니다. (git 무시)`,
);
